import os
import fitz  # PyMuPDF

def generate_sample_arabic_books(output_dir="data/sample_books"):
    os.makedirs(output_dir, exist_ok=True)
    
    # Book 1: Classical Hadith and Fiqh Excerpt
    doc1 = fitz.open()
    
    p1 = doc1.new_page()
    text_p1 = (
        "كتاب الطهارة والصلاة\n\n"
        "الباب الأول: في فضل الوضوء والصلاة المفروضة.\n\n"
        "عن أبي هريرة رضي الله عنه قال: قال رسول الله صلى الله عليه وسلم: "
        "«ألا أدلكم على ما يمحو الله به الخطايا ويرفع به الدرجات؟» قالوا: بلى يا رسول الله. "
        "قال: «إسباغ الوضوء على المكاره، وكثرة الخطا إلى المساجد، وانتظار الصلاة بعد الصلاة، فذلكم الرباط».\n\n"
        "وقد أجمع علماء المسلمين على وجوب إقامة الصلاة وإيتاء الزكاة، "
        "فإن الصلاة عماد الدين من أقامها فقد أقام الدين ومن هدمها فقد هدم الدين."
    )
    p1.insert_text((50, 72), text_p1, fontsize=14)

    p2 = doc1.new_page()
    text_p2 = (
        "الباب الثاني: في آداب طلب العلم ومعاملة المشايخ.\n\n"
        "قال الإمام الشافعي رحمه الله: «أخي لن تنال العلم إلا بستة: سأنبيك عن تفصيلها ببيان: "
        "ذكاء وحرص واجتهاد وبلغة، وصحبة أستاذ وطول زمان».\n\n"
        "وينبغي لطالب العلم أن يخلص النية لله عز وجل في سائر أقواله وأفعاله، "
        "وأن يتجنب الرياء والمباهاة، فإن العلم بلا عمل كالشجر بلا ثمر."
    )
    p2.insert_text((50, 72), text_p2, fontsize=14)

    doc1.save(os.path.join(output_dir, "001_fiqh_and_ilm.pdf"))
    doc1.close()

    # Book 2: History and Geography Excerpt
    doc2 = fitz.open()
    p1_2 = doc2.new_page()
    text_doc2 = (
        "موسوعة التاريخ والجغرافيا الإسلامية\n\n"
        "الفصل الثالث: في وصف المدن والآثار التاريخية القديمة.\n\n"
        "تعد مدينة بغداد ودمشق والقاهرة من أعرق العواصم الإسلامية التي ازدهرت فيها العلوم والآداب. "
        "وقد بنيت دار الحكمة في بغداد في عهد الخليفة العباسي المأمون عام 215 هجرية، "
        "واحتوت على أكثر من 300,000 مجلد في الفلك والطب والرياضيات والفلسفة.\n\n"
        "وقد زار الرحالة ابن بطوطة هذه الحواضر في رحلته الشهيرة التي استمرت نحو 29 عاماً، "
        "وقطع خلالها مسافة تزيد على 120,000 كيلومتر."
    )
    p1_2.insert_text((50, 72), text_doc2, fontsize=14)
    doc2.save(os.path.join(output_dir, "002_tarikh_wa_athar.pdf"))
    doc2.close()

    print("✅ Created sample Arabic PDFs in data/sample_books/")

if __name__ == "__main__":
    generate_sample_arabic_books()
